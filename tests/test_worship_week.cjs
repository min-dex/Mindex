const explicit=build([{source:{service_date:'2026-04-05',service_type_id:'youth',weekly_status:'집회 없음',weekly_reason:'부활절 연합예배'},candidates:[]}]);
assert.equal(explicit[0].entries[4].weeklyReason,'부활절 연합예배');
